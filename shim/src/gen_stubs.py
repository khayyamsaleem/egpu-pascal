"""Emit logging NOT_SUPPORTED stubs for every symbol MAX resolves that a shim .c doesn't define."""
import re, sys
syms, src, out, ret, fail = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5]
log = sys.argv[6] if len(sys.argv) > 6 else "shim_log_stub"      # the shim's logging hook
text = open(src).read()
have = set(re.findall(r"^(?:const\s+)?\w+\s*\**\s*(\w+)\(", text, re.M)) | set(re.findall(r"^CPY\((\w+),", text, re.M))
missing = [s.strip() for s in open(syms) if s.strip() and s.strip() not in have]
with open(out, "w") as f:
    f.write("/* generated by gen_stubs.py: %d stubs */\n#include <stdio.h>\n" % len(missing))
    f.write(("typedef int %s;\n" % ret) if ret != "int" else "")
    f.write("extern void %s(const char *);\n" % log)
    for s in missing:
        f.write('%s %s(void) { %s("%s"); return %s; }\n' % (ret, s, log, s, fail))
print("%s: %d implemented, %d stubbed" % (out, len(have & set(l.strip() for l in open(syms))), len(missing)))
