/*
 * libcuda.so.1 shim for Modular MAX -> GTX 1080 Ti (GP102) over TinyGPU.
 *
 * Stage 1 (this file, SHIM_MODE unset or "sim"): DISCOVERY. Presents one GP102
 * (CC 6.1, 28 SMs, 11 GB, driver 580 / CUDA 13.0), keeps contexts/streams/events
 * as in-process bookkeeping, backs "device" memory with host memory, logs every
 * call to stderr (or $SHIM_LOG), and saves every module image passed to
 * cuModuleLoadDataEx to $SHIM_CAPTURE_DIR/module<N>.bin.  Kernel launches are
 * logged, not executed.
 *
 * Stage 2 (to come): the same entry points forwarded to the macOS-side driver
 * (pascal/nvpascal.py) over a socket; device pointers become GPU VAs.
 *
 * Every symbol MAX resolves (src/cuda_symbols.txt) is exported; the ones not
 * implemented here are generated by gen_stubs.py and return
 * CUDA_ERROR_NOT_SUPPORTED after logging.
 */
