struct mod { int id; };
struct fn { char name[256]; int mod; };
static struct mod mods[256];
static struct fn fns[1024];
static int n_fns;
CUresult cuModuleLoadDataEx(CUmodule *m, const void *image, unsigned nopt, int *opts, void **vals) {
    int id = n_modules++;
    const unsigned char *b = image;
    size_t sz = 0;
    if (b[0] == 0x7f && b[1] == 'E' && b[2] == 'L' && b[3] == 'F') {      /* ELF: size from section headers */
        uint64_t shoff = *(const uint64_t *)(b + 0x28);
        uint16_t shentsize = *(const uint16_t *)(b + 0x3a), shnum = *(const uint16_t *)(b + 0x3c);
        sz = shoff + (size_t)shentsize * shnum;
    } else {
        sz = strlen((const char *)image) + 1;                               /* PTX text */
    }
    const char *dir = getenv("SHIM_CAPTURE_DIR");
    if (dir) {
        char path[512]; snprintf(path, sizeof path, "%s/module%d.bin", dir, id);
        FILE *f = fopen(path, "wb"); if (f) { fwrite(image, 1, sz, f); fclose(f); }
    }
    LOG("cuModuleLoadDataEx(%s, %zu bytes, %u opts) -> module %d", b[0] == 0x7f ? "ELF/cubin" : "PTX", sz, nopt, id);
    mods[id & 255].id = id; *m = &mods[id & 255];
    return CUDA_SUCCESS;
}
