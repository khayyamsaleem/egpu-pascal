CUresult cuModuleGetFunction(CUfunction *f, CUmodule m, const char *name) {
    struct fn *p = &fns[n_fns++ & 1023];
    snprintf(p->name, sizeof p->name, "%s", name); p->mod = ((struct mod *)m)->id;
    *f = p; LOG("cuModuleGetFunction(module %d, \"%s\")", p->mod, name); return CUDA_SUCCESS;
}
